#!/usr/bin/env bash
# Compiles skeleton.vert and skeleton.frag to SPIR-V into recorder_shaders.h, which is checked in so
# neither the desktop nor the APK build needs a shader compiler (docs/recorder.md, Rendering). Run
# it after changing a shader. With --check it writes nothing and fails when the header is stale
# (RecorderShaders.the_checked_in_spirv_matches_the_glsl). The bytes depend on the compiler's
# version, which the header names; --check exits with 125 under another version.

set -euo pipefail

cd "$(dirname "$0")"
version="$(glslangValidator --version | head -1 | sed -E 's/^Glslang Version: //')"
if [ "${1:-}" = "--check" ] && ! grep -qxF "// glslangValidator $version" recorder_shaders.h; then
    echo "recorder_shaders.h was made by another glslangValidator than $version" >&2
    exit 125
fi
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

{
    echo "// Generated by tools/recorder/compile_shaders.sh from skeleton.vert and skeleton.frag; do not edit"
    echo "// glslangValidator $version"
    echo
    echo "#pragma once"
    for stage in vert frag; do
        glslangValidator -V --quiet -o "$work/$stage.spv" "skeleton.$stage" > /dev/null
        echo
        echo "static const uint32_t rc_skeleton_${stage}[] = {"
        # 16 bytes a line by default; macOS's od has no -w, pads its lines and ends with a blank one
        od -An -v -tx4 "$work/$stage.spv" | sed -E '/^ *$/d; s/^ +//; s/ +$//; s/ +/, /g; s/([0-9a-f]{8})/0x\1/g; s/^/    /; s/$/,/'
        echo "};"
    done
} > "$work/recorder_shaders.h"

if [ "${1:-}" = "--check" ]; then
    # No cmp or diff: the CI image has no diffutils
    [ "$(cat "$work/recorder_shaders.h")" = "$(cat recorder_shaders.h)" ]
else
    cp "$work/recorder_shaders.h" recorder_shaders.h
fi
